export const fmtDay = (t: Dict, s: string) =>
  s.replace(/\b(Sat|Sun)\b/g, (m) => t.common.days[m] ?? m).replace(/\b(Nov|Dec)\b/g, (m) => t.common.months[m] ?? m);

